function tx(
  partial: Omit<Transaction, "adminFee" | "book" | "tag" | "note"> & {
    book?: Transaction["book"];
    adminFee?: number;
    tag?: string;
    note?: string;
  },
): Transaction {
  return {
    ...partial,
    book: partial.book ?? "Pribadi",
    adminFee: partial.adminFee ?? 0,
    tag: partial.tag ?? "",
    note: partial.note ?? "",
  };
}

